create table public.assessments (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users (id) on delete cascade,
  title text not null,
  module_code text not null,
  academic_year text not null,
  assessment_type text not null,
  ai_policy text not null,
  group_work_permitted boolean not null default false,
  status text not null default 'draft' check (
    status in ('draft', 'in_review', 'changes_requested', 'approved')
  ),
  content jsonb not null default '{}'::jsonb,
  programme text,
  module_level integer,
  version integer not null default 1 check (version >= 1),
  submitted_at timestamptz,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null check (char_length(trim(display_name)) between 2 and 100),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.reviewer_roles (
  user_id uuid not null references auth.users (id) on delete cascade,
  role text not null check (
    role in (
      'cluster_lead',
      'ai_reviewer',
      'employability_reviewer',
      'teaching_director'
    )
  ),
  assigned_by uuid not null references auth.users (id),
  created_at timestamptz not null default now(),
  primary key (user_id, role)
);

create table public.cluster_lead_scopes (
  user_id uuid not null references auth.users (id) on delete cascade,
  programme text not null check (char_length(trim(programme)) > 0),
  module_level integer not null,
  assigned_by uuid not null references auth.users (id),
  created_at timestamptz not null default now(),
  primary key (user_id, programme, module_level)
);

create table public.assessment_review_assignments (
  assessment_id uuid not null references public.assessments (id) on delete cascade,
  category text not null check (category in ('academic', 'ai', 'employability')),
  reviewer_id uuid references auth.users (id),
  assigned_by uuid references auth.users (id),
  state text not null default 'pending' check (
    state in ('pending', 'approved', 'changes_requested')
  ),
  reviewed_version integer check (reviewed_version is null or reviewed_version >= 1),
  comment text,
  reviewed_at timestamptz,
  assigned_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (assessment_id, category)
);

create table public.assessment_review_events (
  id bigint generated by default as identity primary key,
  assessment_id uuid not null,
  assessment_version integer not null check (assessment_version >= 1),
  category text check (category is null or category in ('academic', 'ai', 'employability')),
  reviewer_id uuid,
  actor_id uuid,
  action text not null check (
    action in ('assigned', 'submitted', 'approved', 'withdrawn', 'invalidated')
  ),
  comment text,
  created_at timestamptz not null default now()
);

