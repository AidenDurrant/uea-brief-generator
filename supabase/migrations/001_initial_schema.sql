create function public.admin_cluster_lead_scopes()
returns table (
  user_id uuid,
  programme text,
  module_level integer,
  assigned_by uuid,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if not private.workflow_has_oversight_access() then
    raise exception 'Administrator or Teaching Director access required'
      using errcode = '42501';
  end if;

  return query
  select
    cls.user_id,
    cls.programme,
    cls.module_level,
    cls.assigned_by,
    cls.created_at
  from public.cluster_lead_scopes as cls
  order by lower(cls.programme), cls.module_level, cls.user_id;
end;
$function$;

create function public.admin_set_cluster_lead_scope(
  target_user_id uuid,
  target_programme text,
  target_module_level integer,
  enabled boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  normalized_programme text;
begin
  if not private.workflow_has_oversight_access() then
    raise exception 'Administrator or Teaching Director access required'
      using errcode = '42501';
  end if;

  normalized_programme := nullif(trim(target_programme), '');
  if target_user_id is null
    or normalized_programme is null
    or target_module_level is null then
    raise exception 'User, programme, and module level are required'
      using errcode = '22023';
  end if;

  if enabled is null then
    raise exception 'enabled must be true or false' using errcode = '22023';
  end if;

  if enabled and not exists (
    select 1
    from public.reviewer_roles as rr
    where rr.user_id = target_user_id
      and rr.role = 'cluster_lead'
  ) then
    raise exception 'User must hold the cluster_lead role'
      using errcode = '22023';
  end if;

  if enabled then
    insert into public.cluster_lead_scopes (
      user_id,
      programme,
      module_level,
      assigned_by
    ) values (
      target_user_id,
      normalized_programme,
      target_module_level,
      auth.uid()
    )
    on conflict (user_id, programme, module_level) do update
      set assigned_by = excluded.assigned_by,
          created_at = now();
  else
    delete from public.cluster_lead_scopes as cls
    where cls.user_id = target_user_id
      and cls.programme = normalized_programme
      and cls.module_level = target_module_level;
  end if;
end;
$function$;
