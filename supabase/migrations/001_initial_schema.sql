create function private.workflow_has_oversight_access()
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select auth.uid() is not null
    and (
      exists (
        select 1
        from public.admin_users as au
        where au.user_id = auth.uid()
      )
      or exists (
        select 1
        from public.reviewer_roles as rr
        where rr.user_id = auth.uid()
          and rr.role = 'teaching_director'
      )
    );
$function$;

create function private.workflow_user_can_review_assessment(
  candidate_user_id uuid,
  target_assessment_id uuid,
  target_category text
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select candidate_user_id is not null
    and target_category in ('academic', 'ai', 'employability')
    and exists (
      select 1
      from public.assessments as a
      where a.id = target_assessment_id
        and a.owner_id <> candidate_user_id
        and (
          (
            target_category = 'academic'
            and exists (
              select 1
              from public.reviewer_roles as rr
              join public.cluster_lead_scopes as cls
                on cls.user_id = rr.user_id
               and lower(trim(cls.programme)) = lower(trim(a.programme))
               and cls.module_level = a.module_level
              where rr.user_id = candidate_user_id
                and rr.role = 'cluster_lead'
            )
          )
          or (
            target_category = 'ai'
            and exists (
              select 1
              from public.reviewer_roles as rr
              where rr.user_id = candidate_user_id
                and rr.role = 'ai_reviewer'
            )
          )
          or (
            target_category = 'employability'
            and exists (
              select 1
              from public.reviewer_roles as rr
              where rr.user_id = candidate_user_id
                and rr.role = 'employability_reviewer'
            )
          )
        )
    );
$function$;

