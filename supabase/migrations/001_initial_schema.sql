create function public.admin_set_workflow_role(
  target_user_id uuid,
  target_role text,
  enabled boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if not private.workflow_has_oversight_access() then
    raise exception 'Administrator or Teaching Director access required'
      using errcode = '42501';
  end if;

  if target_role is null or target_role not in (
    'cluster_lead',
    'ai_reviewer',
    'employability_reviewer',
    'teaching_director'
  ) then
    raise exception 'Invalid workflow role: %', target_role using errcode = '22023';
  end if;

  if enabled is null then
    raise exception 'enabled must be true or false' using errcode = '22023';
  end if;

  if target_user_id is null or not exists (
    select 1
    from public.profiles as p
    where p.user_id = target_user_id
  ) then
    raise exception 'Cannot set workflow role without an existing profile: %', target_user_id
      using errcode = '22023';
  end if;

  if enabled then
    insert into public.reviewer_roles (user_id, role, assigned_by)
    values (target_user_id, target_role, auth.uid())
    on conflict (user_id, role) do update
      set assigned_by = excluded.assigned_by;
  else
    if target_role = 'cluster_lead' then
      delete from public.cluster_lead_scopes as cls
      where cls.user_id = target_user_id;
    end if;

    delete from public.reviewer_roles as rr
    where rr.user_id = target_user_id
      and rr.role = target_role;
  end if;
end;
$function$;

create function public.admin_review_assignments()
returns table (
  assessment_id uuid,
  category text,
  reviewer_id uuid,
  reviewer_name text,
  state text,
  reviewed_version integer,
  comment text,
  reviewed_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if not private.workflow_has_oversight_access() then
    raise exception 'Administrator or Teaching Director access required'
      using errcode = '42501';
  end if;

  return query
  select
    ara.assessment_id,
    ara.category,
    ara.reviewer_id,
    p.display_name as reviewer_name,
    ara.state,
    ara.reviewed_version,
    ara.comment,
    ara.reviewed_at
  from public.assessment_review_assignments as ara
  left join public.profiles as p on p.user_id = ara.reviewer_id
