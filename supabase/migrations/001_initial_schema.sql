create function public.submit_assessment_for_review(
  target_assessment_id uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  assessment_current_version integer;
  assessment_current_status text;
  assessment_owner_id uuid;
  assessment_programme text;
  assessment_module_level integer;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  select a.version, a.status, a.owner_id, a.programme, a.module_level
  into assessment_current_version, assessment_current_status,
    assessment_owner_id, assessment_programme, assessment_module_level
  from public.assessments as a
  where a.id = target_assessment_id
    and a.owner_id = auth.uid()
  for update;

  if not found then
    raise exception 'Assessment owner access required' using errcode = '42501';
  end if;

  if assessment_current_status <> 'draft' then
    raise exception 'Only draft assessments can be submitted for review'
      using errcode = '22023';
  end if;

  if assessment_programme is null or assessment_module_level is null then
    raise exception 'Programme and module level are required before submission'
      using errcode = '22023';
  end if;

  if not exists (
    select 1
    from public.reviewer_roles as rr
    join public.cluster_lead_scopes as cls
      on cls.user_id = rr.user_id
     and lower(trim(cls.programme)) = lower(trim(assessment_programme))
     and cls.module_level = assessment_module_level
    where rr.role = 'cluster_lead'
      and rr.user_id <> assessment_owner_id
  ) then
    raise exception 'An eligible non-owner cluster lead is required for this programme and level'
      using errcode = '22023';
  end if;

  if not exists (
    select 1
    from public.reviewer_roles as rr
    where rr.role = 'ai_reviewer'
      and rr.user_id <> assessment_owner_id
  ) then
    raise exception 'An eligible non-owner AI reviewer is required'
      using errcode = '22023';
  end if;

  if not exists (
    select 1
    from public.reviewer_roles as rr
    where rr.role = 'employability_reviewer'
      and rr.user_id <> assessment_owner_id
  ) then
    raise exception 'An eligible non-owner employability reviewer is required'
      using errcode = '22023';
  end if;

  insert into public.assessment_review_assignments (
    assessment_id,
    category,
    reviewer_id,
    assigned_by,
    state,
    reviewed_version,
    comment,
    reviewed_at,
    assigned_at
  )
  select
    target_assessment_id,
    required_categories.category,
    null,
    null,
    'pending',
    null,
    null,
    null,
    now()
  from (
    values ('academic'::text), ('ai'::text), ('employability'::text)
  ) as required_categories(category)
  on conflict (assessment_id, category) do update
    set reviewer_id = null,
        assigned_by = null,
        state = 'pending',
        reviewed_version = null,
        comment = null,
        reviewed_at = null,
        assigned_at = excluded.assigned_at;

  perform pg_catalog.set_config('app.workflow_transition', 'allowed', true);

  update public.assessments as a
  set status = 'in_review',
      submitted_at = now(),
      approved_at = null
  where a.id = target_assessment_id;

  insert into public.assessment_review_events (
    assessment_id,
    assessment_version,
    actor_id,
    action
  ) values (
    target_assessment_id,
    assessment_current_version,
    auth.uid(),
    'submitted'
  );
end;
$function$;
