create function public.assessment_can_export_final(
  target_assessment_id uuid
)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  assessment_current_version integer;
  assessment_current_status text;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  select a.version, a.status
  into assessment_current_version, assessment_current_status
  from public.assessments as a
  where a.id = target_assessment_id
    and a.owner_id = auth.uid();

  if not found then
    raise exception 'Only the assessment owner can export the final brief'
      using errcode = '42501';
  end if;

  return assessment_current_status = 'approved'
    and (
      select count(*) = 3
        and count(distinct ara.category) = 3
      from public.assessment_review_assignments as ara
      where ara.assessment_id = target_assessment_id
        and ara.category in ('academic', 'ai', 'employability')
        and ara.state = 'approved'
        and ara.reviewer_id is not null
        and ara.reviewed_version = assessment_current_version
    );
end;
$function$;
create function public.review_queue()
returns table (
  assessment_id uuid,
  title text,
  module_code text,
  owner_id uuid,
  owner_name text,
  category text,
  reviewer_id uuid,
  state text,
  assessment_version integer,
  reviewed_version integer,
  comment text,
  submitted_at timestamptz,
  status text,
  content jsonb,
  updated_at timestamptz,
  can_review boolean
)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  caller_has_oversight boolean;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  caller_has_oversight := private.workflow_has_oversight_access();

  return query
  select
    a.id as assessment_id,
    a.title,
    a.module_code,
    a.owner_id,
    owner_profile.display_name as owner_name,
    required_categories.category,
    ara.reviewer_id,
    coalesce(ara.state, 'pending') as state,
    a.version as assessment_version,
    ara.reviewed_version,
    ara.comment,
    a.submitted_at,
    a.status,
    a.content,
    a.updated_at,
    (
      a.status in ('in_review', 'approved')
      and private.workflow_user_can_review_assessment(
        auth.uid(), a.id, required_categories.category
      )
    ) as can_review
  from public.assessments as a
  cross join (
    values ('academic'::text), ('ai'::text), ('employability'::text)
  ) as required_categories(category)
  left join public.assessment_review_assignments as ara
    on ara.assessment_id = a.id
   and ara.category = required_categories.category
  left join public.profiles as owner_profile on owner_profile.user_id = a.owner_id
  where caller_has_oversight
    or (
      a.status <> 'draft'
      and private.workflow_user_can_review_assessment(
        auth.uid(), a.id, required_categories.category
      )
    )
  order by a.submitted_at desc nulls last,
    a.updated_at desc,
    case required_categories.category
      when 'academic' then 1
      when 'ai' then 2
      when 'employability' then 3
    end;
end;
$function$;

