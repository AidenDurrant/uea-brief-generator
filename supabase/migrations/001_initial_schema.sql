create function public.admin_demote_user(target_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if not private.workflow_has_oversight_access() then
    raise exception 'Administrator or Teaching Director access required'
      using errcode = '42501';
  end if;

  if target_user_id is null then
    raise exception 'Administrator user is required' using errcode = '22023';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtext('public.admin_users_role_management')
  );

  if not exists (
    select 1
    from public.admin_users as au
    where au.user_id = target_user_id
  ) then
    return;
  end if;

  if target_user_id = auth.uid() then
    raise exception 'You cannot demote your own administrator account'
      using errcode = '22023';
  end if;

  if (select count(*) from public.admin_users) <= 1 then
    raise exception 'The final administrator cannot be demoted'
      using errcode = '22023';
  end if;

  delete from public.admin_users as au
  where au.user_id = target_user_id;
end;
$function$;

create function public.admin_assessment_statistics()
returns table (
  total_assessments bigint,
  unique_owners bigint,
  group_work_assessments bigint,
  assessments_by_status jsonb,
  assessments_by_type jsonb,
  assessments_by_academic_year jsonb
)
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if not private.workflow_has_oversight_access() then
    raise exception 'Administrator or Teaching Director access required'
      using errcode = '42501';
  end if;

  return query
  select
    count(*)::bigint,
    count(distinct assessments.owner_id)::bigint,
    count(*) filter (where assessments.group_work_permitted)::bigint,
    coalesce(
      (
        select jsonb_object_agg(status_counts.status, status_counts.assessment_count)
        from (
          select a.status, count(*)::bigint as assessment_count
          from public.assessments as a
          group by a.status
        ) as status_counts
      ),
      '{}'::jsonb
    ),
    coalesce(
      (
        select jsonb_object_agg(type_counts.assessment_type, type_counts.assessment_count)
        from (
          select a.assessment_type, count(*)::bigint as assessment_count
          from public.assessments as a
          group by a.assessment_type
        ) as type_counts
      ),
      '{}'::jsonb
    ),
    coalesce(
      (
        select jsonb_object_agg(year_counts.academic_year, year_counts.assessment_count)
        from (
          select a.academic_year, count(*)::bigint as assessment_count
          from public.assessments as a
          group by a.academic_year
        ) as year_counts
      ),
      '{}'::jsonb
    )
  from public.assessments as assessments;
end;
$function$;
create function public.record_assessment_review(
  target_assessment_id uuid,
  target_category text,
  decision text,
  review_comment text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  assessment_current_version integer;
  assessment_current_status text;
  assessment_owner_id uuid;
  category_current_state text;
  category_reviewed_version integer;
  normalized_decision text;
  normalized_comment text;
  all_categories_approved boolean;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if target_category is null
    or target_category not in ('academic', 'ai', 'employability') then
    raise exception 'Invalid review category: %', target_category
      using errcode = '22023';
  end if;

  normalized_decision := lower(trim(decision));
  if normalized_decision is null
    or normalized_decision not in ('approve', 'withdraw') then
    raise exception 'Decision must be approve or withdraw'
      using errcode = '22023';
  end if;

  normalized_comment := nullif(trim(review_comment), '');
  if normalized_decision = 'withdraw'
    and (normalized_comment is null or char_length(normalized_comment) < 2) then
    raise exception 'A withdrawal comment of at least 2 characters is required'
      using errcode = '22023';
  end if;

  select a.version, a.status, a.owner_id
  into assessment_current_version, assessment_current_status, assessment_owner_id
  from public.assessments as a
  where a.id = target_assessment_id
  for update;

  if not found then
    raise exception 'Assessment not found: %', target_assessment_id
      using errcode = '22023';
  end if;

  if assessment_current_status not in ('in_review', 'approved') then
    raise exception 'Assessment is not available for review'
      using errcode = '22023';
  end if;

  if auth.uid() = assessment_owner_id then
    raise exception 'Assessment owners cannot review their own assessment'
      using errcode = '42501';
  end if;

  if not private.workflow_user_can_review_assessment(
    auth.uid(), target_assessment_id, target_category
  ) then
    raise exception 'Reviewer role and scope eligibility required'
      using errcode = '42501';
  end if;

  select ara.state, ara.reviewed_version
  into category_current_state, category_reviewed_version
  from public.assessment_review_assignments as ara
  where ara.assessment_id = target_assessment_id
    and ara.category = target_category
  for update;

  if not found then
    raise exception 'Assessment category is not pending review'
      using errcode = '22023';
  end if;

  if normalized_decision = 'approve'
    and category_current_state = 'approved'
    and category_reviewed_version = assessment_current_version then
    raise exception 'This category is already approved for the current version'
      using errcode = '22023';
  end if;

  perform pg_catalog.set_config('app.workflow_transition', 'allowed', true);

  if normalized_decision = 'withdraw' then
    update public.assessment_review_assignments as ara
    set reviewer_id = auth.uid(),
        assigned_by = null,
        state = 'changes_requested',
        reviewed_version = assessment_current_version,
        comment = normalized_comment,
        reviewed_at = now()
    where ara.assessment_id = target_assessment_id
      and ara.category = target_category;

    update public.assessments as a
    set status = 'changes_requested',
        approved_at = null
    where a.id = target_assessment_id;

    insert into public.assessment_review_events (
      assessment_id,
      assessment_version,
      category,
      reviewer_id,
      actor_id,
      action,
      comment
    ) values (
      target_assessment_id,
      assessment_current_version,
      target_category,
      auth.uid(),
      auth.uid(),
      'withdrawn',
      normalized_comment
    );
  else
    update public.assessment_review_assignments as ara
    set reviewer_id = auth.uid(),
        assigned_by = null,
        state = 'approved',
        reviewed_version = assessment_current_version,
        comment = normalized_comment,
        reviewed_at = now()
    where ara.assessment_id = target_assessment_id
      and ara.category = target_category;

    insert into public.assessment_review_events (
      assessment_id,
      assessment_version,
      category,
      reviewer_id,
      actor_id,
      action,
      comment
    ) values (
      target_assessment_id,
      assessment_current_version,
      target_category,
      auth.uid(),
      auth.uid(),
      'approved',
      normalized_comment
    );

    select count(*) = 3
      and count(distinct ara.category) = 3
    into all_categories_approved
    from public.assessment_review_assignments as ara
    where ara.assessment_id = target_assessment_id
      and ara.category in ('academic', 'ai', 'employability')
      and ara.state = 'approved'
      and ara.reviewer_id is not null
      and ara.reviewed_version = assessment_current_version;

    update public.assessments as a
    set status = case
          when all_categories_approved then 'approved'
          else 'in_review'
        end,
        approved_at = case
          when all_categories_approved then now()
          else null
        end
    where a.id = target_assessment_id;
  end if;
end;
$function$;

