create function private.prepare_assessment_version_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  brief_changed boolean;
  workflow_transition_allowed boolean;
begin
  new.programme := nullif(trim(new.programme), '');

  if tg_op = 'INSERT' then
    new.version := 1;
    new.status := 'draft';
    new.submitted_at := null;
    new.approved_at := null;
    return new;
  end if;

  brief_changed :=
    new.title is distinct from old.title
    or new.module_code is distinct from old.module_code
    or new.academic_year is distinct from old.academic_year
    or new.assessment_type is distinct from old.assessment_type
    or new.ai_policy is distinct from old.ai_policy
    or new.group_work_permitted is distinct from old.group_work_permitted
    or new.content is distinct from old.content
    or new.programme is distinct from old.programme
    or new.module_level is distinct from old.module_level;
  workflow_transition_allowed :=
    coalesce(pg_catalog.current_setting('app.workflow_transition', true), '') = 'allowed';

  if brief_changed then
    if old.status <> 'draft' then
      new.version := old.version + 1;
      new.status := 'draft';
      new.submitted_at := null;
      new.approved_at := null;
    else
      new.version := old.version;
      new.status := old.status;
      new.submitted_at := old.submitted_at;
      new.approved_at := old.approved_at;
    end if;
  elsif (
    new.version is distinct from old.version
    or new.status is distinct from old.status
    or new.submitted_at is distinct from old.submitted_at
    or new.approved_at is distinct from old.approved_at
  ) and not workflow_transition_allowed then
    raise exception 'Assessment workflow fields can only be changed through workflow actions'
      using errcode = '42501';
  end if;

  return new;
end;
$function$;

create function private.invalidate_assessment_reviews()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  update public.assessment_review_assignments as ara
  set reviewer_id = null,
      assigned_by = null,
      state = 'pending',
      reviewed_version = null,
      comment = null,
      reviewed_at = null
  where ara.assessment_id = new.id;

  insert into public.assessment_review_events (
    assessment_id,
    assessment_version,
    actor_id,
    action,
    comment
  ) values (
    new.id,
    new.version,
    auth.uid(),
    'invalidated',
    'Assessment brief changed; version ' || old.version::text
      || ' reviews were invalidated by version ' || new.version::text
  );

  return new;
end;
$function$;

